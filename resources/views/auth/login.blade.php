<script>
    function setRole(role) {
        const agentBtn = document.getElementById('role-agente');
        const adminBtn = document.getElementById('role-admin');
        const roleInput = document.getElementById('role-input');

        roleInput.value = role;

        if (role === 'agente') {
            agentBtn.classList.add('bg-white', 'text-primary', 'shadow-sm');
            agentBtn.classList.remove('text-on-surface-variant');
            adminBtn.classList.remove('bg-white', 'text-primary', 'shadow-sm');
            adminBtn.classList.add('text-on-surface-variant');
        } else {
            adminBtn.classList.add('bg-white', 'text-primary', 'shadow-sm');
            adminBtn.classList.remove('text-on-surface-variant');
            agentBtn.classList.remove('bg-white', 'text-primary', 'shadow-sm');
            agentBtn.classList.add('text-on-surface-variant');
        }
    }

    // Simple button press effect for "Iniciar Sesión"
    document.querySelector('form').addEventListener('submit', function(e) {
        const btn = e.target.querySelector('button[type="submit"]');
        const originalText = btn.innerText;
        btn.innerText = 'Cargando...';
        btn.disabled = true;
        btn.classList.add('opacity-80', 'cursor-not-allowed');
    });
</script>
